"""Record where the vendored checkers and their dependencies come from, from local git clones of
marin-community/marin, marin-community/evalchemy and allenai/IFBench.

Writes vendor/PROVENANCE.md with:
- the Evalchemy commit that Marin's main branch pins;
- three Evalchemy commits (the one that added the IFBench checkers, the one marin#10060 audited,
  Marin's pin), the blobs of the three checker files at each, and the commits that changed those
  files in between (none);
- the IFBench commits (the version Evalchemy vendored, the six-verifier fix, upstream main) and the
  merge that brought the fix into upstream main;
- how Evalchemy's instructions.py differs from upstream's at the vendored version;
- the grader dependencies in Evalchemy's uv.lock;
- how Evalchemy names the IFBench_test source.

Usage: python -I provenance.py <marin clone> <evalchemy clone> <IFBench clone> [out.md]
"""

import difflib
import re
import subprocess
import sys
from pathlib import Path

ADDED = "ab7ae27"  # evalchemy#23 added eval/chat_benchmarks/IFBench with these checker files
AUDITED = "97fffeb"  # the commit marin#10060 audited
IFBENCH = {"357d098": "the version Evalchemy vendored", "1d62c1d": "the six-verifier fix", "1c40f0c": "upstream main"}
CHECKERS = tuple(f"eval/chat_benchmarks/IFBench/{name}"
                 for name in ("instructions.py", "instructions_registry.py", "instructions_util.py"))
PIN_FILE = "lib/marin/src/marin/external_dependencies.py"
OUT = Path(__file__).resolve().parents[1] / "vendor" / "PROVENANCE.md"


def git(repo: str, *args: str) -> str:
    return subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True, encoding="utf-8",
                          check=True).stdout.strip()


def commit_line(repo: str, rev: str) -> str:
    sha, authored, committed, author, subject = git(
        repo, "log", "-1", "--format=%H|%ad|%cd|%an|%s", "--date=short", rev).split("|", 4)
    dates = authored if authored == committed else f"authored {authored}, committed {committed}"
    return f"`{sha}` ({dates}, {author}): {subject}"


def marin_pin(marin: str) -> tuple[str, str]:
    """The Evalchemy commit pinned on Marin's main branch, and the Marin commit it was read from."""
    rev = "origin/main" if git(marin, "branch", "-r", "--list", "origin/main") else "HEAD"
    source = git(marin, "show", f"{rev}:{PIN_FILE}")
    block = source[source.index("EVALCHEMY = ExternalDependency("):]
    return re.search(r'commit="([0-9a-f]{40})"', block).group(1), git(marin, "rev-parse", rev)


def lock_versions(repo: str, rev: str, names: tuple[str, ...]) -> dict:
    lines = git(repo, "show", f"{rev}:uv.lock").splitlines()
    found = {}
    for i, line in enumerate(lines[:-1]):
        for name in names:
            if line == f'name = "{name}"' and lines[i + 1].startswith("version = "):
                found[name] = lines[i + 1].split('"')[1]
    return {name: found.get(name, "absent") for name in names}


def main(marin: str, evalchemy: str, ifbench: str, out: str = str(OUT)) -> None:
    pin, marin_rev = marin_pin(marin)
    marin_date = git(marin, "log", "-1", "--format=%cd", "--date=short", marin_rev)
    short_pin = pin[:7]
    lines = ["# Provenance of the vendored checkers", "",
             "Generated by `analysis/provenance.py` from git clones of `marin-community/marin`, "
             "`marin-community/evalchemy` and `allenai/IFBench`.", "",
             "## Evalchemy", "",
             f"Marin's main branch at `{marin_rev[:10]}` ({marin_date}) pins Evalchemy `{pin}` in `{PIN_FILE}`.", ""]
    roles = {ADDED: "added the IFBench checkers (evalchemy#23)", AUDITED: "the commit marin#10060 audited",
             short_pin: f"Marin's pin on {marin_date}"}
    for rev, role in roles.items():
        blobs = ", ".join(f"`{git(evalchemy, 'rev-parse', f'{rev}:{path}')[:7]}`" for path in CHECKERS)
        lines.append(f"- {role}: {commit_line(evalchemy, rev)}. Checker blobs: {blobs}.")
    changes = git(evalchemy, "log", "--format=%h %s", f"{ADDED}..{pin}", "--", *CHECKERS)
    lines += ["", f"Commits that changed the checker files between `{ADDED}` and `{short_pin}`: "
              f"{changes or 'none'}.", "", "## IFBench", ""]
    for rev, role in IFBENCH.items():
        lines.append(f"- {role}: {commit_line(ifbench, rev)}.")
    # The first commit on main's first-parent history that contains the fix is the merge that brought it in.
    for rev in git(ifbench, "rev-list", "--first-parent", "--reverse", "1c40f0c").splitlines():
        if subprocess.run(["git", "-C", ifbench, "merge-base", "--is-ancestor", "1d62c1d", rev]).returncode == 0:
            sha, date, subject = git(ifbench, "log", "-1", "--format=%h|%cd|%s", "--date=short", rev).split("|", 2)
            lines.append(f"- The fix reached upstream main in `{sha}` ({date}): {subject}.")
            break

    vendored = git(evalchemy, "show", f"{pin}:{CHECKERS[0]}").splitlines()
    upstream_path = next(p for p in ("ifbench/instructions.py", "instructions.py")
                         if git(ifbench, "ls-tree", "--name-only", "357d098", p))
    upstream = git(ifbench, "show", f"357d098:{upstream_path}").splitlines()
    changed = [l for l in difflib.unified_diff(upstream, vendored, lineterm="", n=0)
               if l[:1] in "+-" and not l.startswith(("+++", "---"))]
    lines += ["", "## Evalchemy's checkers against upstream", "",
              f"`{CHECKERS[0]}` at `{short_pin}` and `{upstream_path}` at `357d098` differ only in these lines:", ""]
    lines += [f"    {l}" for l in changed]

    names = ("nltk", "emoji", "syllapy")
    lines += ["", "## Grader dependencies in Evalchemy's uv.lock", "", "| Commit | " + " | ".join(names) + " |",
              "|---|" + "---|" * len(names)]
    for rev in (ADDED, AUDITED, short_pin):
        versions = lock_versions(evalchemy, rev, names)
        lines.append(f"| `{rev}` | " + " | ".join(versions[n] for n in names) + " |")

    lines += ["", "## How Evalchemy names the test data", ""]
    for rev in (AUDITED, short_pin):
        hits = git(evalchemy, "grep", "-n", "-E", r"SourceRef\(|load_dataset\(", rev, "--",
                   "eval/chat_benchmarks/IFBench").splitlines()
        lines += [f"    {hit}" for hit in hits]
    lines += ["", "Neither commit names a dataset revision, so the dataset's current main is loaded. The audit pins `2e8a48de`, "
              "which the Hugging Face commits API (`/api/datasets/allenai/IFBench_test/commits/main`) listed on "
              "2026-10-16 as the head of main, committed 2025-10-17.", ""]
    Path(out).write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main(*sys.argv[1:5])
