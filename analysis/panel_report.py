"""Render the panel analysis (analysis.json from panel_analysis.py) as the Markdown tables of the
panel section in reports/AUDIT.md, so the numbers in those tables come from one file.

Usage: python -I panel_report.py <analysis.json>
"""

import json
import sys

sys.stdout.reconfigure(encoding="utf-8")


def short(config: str) -> str:
    name = config.split("__", 1)[1]
    for old, new in (("-Instruct-v0.3", ""), ("-Instruct-2501", ""), ("-Instruct", ""), ("Llama-3.1-", ""),
                     ("__thinking", " (thinking)")):
        name = name.replace(old, new)
    return name


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def signed(x: float) -> str:
    return f"{100 * x:+.1f}".replace("-", "−")


NAMES = {"marin_strict": "Marin strict", "marin_loose": "Marin loose", "upstream_strict": "Upstream strict",
         "upstream_loose": "Upstream loose", "fixes_only": "Fixes only", "proposed": "Proposed"}


def main(path: str) -> None:
    r = json.load(open(path, encoding="utf-8"))
    acc, effect = r["accuracy"], r["grader_effect"]
    order = sorted(acc, key=lambda c: -acc[c]["marin_strict"][0])

    print("# Model-panel tables\n")
    print("Generated by `analysis/panel_report.py` from `results/panel/analysis.json`. Accuracies are "
          "percentages, differences are percentage points, and brackets hold 95% bootstrap intervals over "
          "prompts.\n")
    print("### Accuracy and grader effect (greedy, prompt-level, 300 prompts)\n")
    print("| Model | Marin strict | Marin loose | Upstream strict | Fixes only − Marin | Proposed − Marin | Truncated |")
    print("|---|---|---|---|---|---|---|")
    for c in order:
        a, e, d = acc[c], effect[c], r["diagnostics"][c]
        cells = [
            f"{pct(a['marin_strict'][0])} [{pct(a['marin_strict'][1])}, {pct(a['marin_strict'][2])}]",
            pct(a["marin_loose"][0]), pct(a["upstream_strict"][0]),
            f"{signed(e['fixes_only'][0])} [{signed(e['fixes_only'][1])}, {signed(e['fixes_only'][2])}]",
            f"{signed(e['proposed'][0])} [{signed(e['proposed'][1])}, {signed(e['proposed'][2])}]",
            f"{pct(d['truncated'])}%",
        ]
        print(f"| {short(c)} | " + " | ".join(cells) + " |")

    print("\n### Rankings\n")
    print("Models from best to worst under each grader:\n")
    for grader, order_g in r["rankings"].items():
        print(f"- {NAMES[grader]}: " + ", ".join(short(c) for c in order_g))
    print("\nPairs whose order differs from Marin strict: the difference a − b under Marin strict, then under "
          "the named grader with its 95% paired interval.\n")
    for f in r["flips"]:
        print(f"- {NAMES[f['grader']]}: {short(f['a'])} vs {short(f['b'])}: {signed(f['marin_strict_diff'])}, then "
              f"{signed(f['diff'])} [{signed(f['ci'][0])}, {signed(f['ci'][1])}]")
    if "sampled_rankings" in r:
        print(f"\nKendall's tau between the Marin strict and proposed rankings by mean sampled accuracy: "
              f"{r['sampled_rankings']['tau']:.3f}")

    print("\n### Greedy reruns\n")
    print("| Model | Identical, same order | Identical, shuffled | Prompt verdicts changed (same order) | "
          "Marin strict change (points) | "
          "Identical, batch-invariant | Default vs batch-invariant identical |")
    print("|---|---|---|---|---|---|---|")
    for c in order:
        rr = r["rerun"].get(c, {})
        same = rr.get("same order rerun")
        shuf = rr.get("shuffled order")
        bi = rr.get("batch-invariant, shuffled")
        dvb = rr.get("default vs batch-invariant")
        cells = [
            f"{pct(same['identical'])}%" if same else "–",
            f"{pct(shuf['identical'])}%" if shuf else "–",
            str(same["prompt_verdicts_changed"]) if same else "–",
            signed(same["delta"]["marin_strict"]) if same else "–",
            f"{pct(bi['identical'])}%" if bi else "–",
            f"{pct(dvb['identical'])}%" if dvb else "–",
        ]
        print(f"| {short(c)} | " + " | ".join(cells) + " |")

    print("\n### Sampled runs (temperature 0.7)\n")
    print("| Model | Runs | Marin strict mean (min–max) | Proposed mean (min–max) |")
    print("|---|---|---|---|")
    for c in order:
        s = r["samples"].get(c)
        if not s:
            continue
        m, p = s["marin_strict"], s["proposed"]
        print(f"| {short(c)} | {len(m)} | {pct(sum(m) / len(m))} ({pct(min(m))}–{pct(max(m))}) | "
              f"{pct(sum(p) / len(p))} ({pct(min(p))}–{pct(max(p))}) |")

    print("\n### Thinking: visible answer vs raw text\n")
    for c, t in r["thinking"].items():
        d = r["diagnostics"][c]
        print(f"- {short(c)}: Marin strict {pct(t['marin_strict'][0])} vs {pct(t['marin_strict'][1])} raw; "
              f"proposed {pct(t['proposed'][0])} vs {pct(t['proposed'][1])}; unclosed reasoning {pct(d['unclosed'])}%, "
              f"truncated {pct(d['truncated'])}%")

    print("\n### Diagnostics (greedy)\n")
    print("| Model | Mean tokens | Truncated | Degenerate | Constraint passes (Marin strict) | of which truncated or "
          "degenerate |")
    print("|---|---|---|---|---|---|")
    for c in order:
        d = r["diagnostics"][c]
        print(f"| {short(c)} | {d['tokens']:.0f} | {pct(d['truncated'])}% | {pct(d['degenerate'])}% | "
              f"{d['passes_marin_strict']} | {d['bad_passes_marin_strict']} |")

    print("\n### Loose rescues (all runs)\n")
    res = r["loose_rescues"]
    total = sum(v[0] for v in res.values())
    print(f"{total} constraint verdicts fail Marin strict but pass Marin loose; "
          f"{sum(v[1] for v in res.values())} of them pass proposed. The eight types with the most:\n")
    for iid, (n, valid) in sorted(res.items(), key=lambda x: -x[1][0])[:8]:
        print(f"- {iid}: {n}, of which {valid} pass proposed")
    print("\nRuns left out as incomplete:\n")
    for note in r["skipped"]:
        print(f"- {note}")


if __name__ == "__main__":
    main(sys.argv[1])
